namespace App\RSpade\Core\Companion;

use App\RSpade\Core\Manifest\ManifestSupport_Abstract;
use App\RSpade\Core\Paths\Rsx_Project_Paths;

/**
 * Writes what rsx-companiond and a companion's process read from the build:
 *
 *   build/companions/<name>/descriptor.json   how to run it, so the daemon needs no PHP
 *   build/companions/<name>/client.js         a client naming exactly its endpoints
 *
 * Runs with the stub generators at the tail of the module list, so a build that failed any
 * validation publishes nothing. Content-compared before writing, and a companion no longer
 * declared has its directory removed. Deterministic: the output is a function of the code and
 * the rsx.companions config, and the seal lists these files (Rsx_Prod_Seal). A descriptor never
 * holds a secret: the instance secret is derived per start and passed by environment.
 *
 * The shapes are the wire contract (rsx:man companion_apps).
 */
class Companion_Descriptor_ManifestSupport extends ManifestSupport_Abstract
{
    /** The descriptor's own format, for the daemon to refuse one it cannot read. */
    public const DESCRIPTOR_SCHEMA = 1;

    public static function get_name(): string
    {
        return 'Companion Descriptors';
    }

    /**
     * Regenerate every companion's two files, and drop the rest.
     */
    public static function process(array &$manifest_data, array $changed_files, array $removed_files): void
    {
        $companions = $manifest_data['data']['companions'] ?? [];

        foreach ($companions as $name => $companion) {
            static::__write(Rsx_Project_Paths::companion_descriptor_file($name), static::descriptor_json($companion));
            static::__write(Rsx_Project_Paths::companion_client_file($name), static::client_source($companion));
        }

        static::__prune(array_keys($companions));
    }

    /**
     * One companion's descriptor.
     */
    public static function descriptor_json(array $companion): string
    {
        return json_encode([
            'schema' => self::DESCRIPTOR_SCHEMA,
            'name' => $companion['name'],
            'description' => $companion['description'],
            'class' => $companion['class'],
            'directory' => $companion['directory'],
            'command' => $companion['command'],
            'working_directory' => $companion['working_directory'],
            'environment' => (object) $companion['environment'],
            'shutdown_grace_seconds' => $companion['shutdown_grace_seconds'],
            'restart_policy' => $companion['restart_policy'],
            'restart_backoff_initial_seconds' => $companion['restart_backoff_initial_seconds'],
            'restart_backoff_ceiling_seconds' => $companion['restart_backoff_ceiling_seconds'],
            'single_instance' => $companion['single_instance'],
            'on_code_change' => $companion['on_code_change'],
            'endpoints_hash' => $companion['endpoints_hash'],
            'source_hash' => $companion['source_hash'],
            'endpoints' => array_keys($companion['endpoints']),
            'logging' => config('rsx.companions.logging'),
            'history_keep' => config('rsx.companions.history_keep'),
            'output_stream_max_lines' => config('rsx.companions.output_stream_max_lines'),
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n";
    }

    /**
     * The companion-side twin of the Ajax JS stubs: a CommonJS module the SDK binds to its
     * call(), so a name that is not an endpoint is no method at all.
     */
    public static function client_source(array $companion): string
    {
        $endpoints = array_keys($companion['endpoints']);

        $methods = '';
        foreach ($endpoints as $endpoint) {
            $methods .= "        {$endpoint}: (params, options) => call('{$endpoint}', params, options),\n";
        }

        return "'use strict';\n"
            . "// GENERATED by the manifest build for companion '{$companion['name']}'. Do not edit.\n"
            . "module.exports = {\n"
            . "    name: '{$companion['name']}',\n"
            . "    endpoints_hash: '{$companion['endpoints_hash']}',\n"
            . '    endpoints: ' . json_encode($endpoints, JSON_UNESCAPED_SLASHES) . ",\n"
            . "    bind: (call) => ({\n{$methods}    }),\n"
            . "};\n";
    }

    /**
     * Write only when the content changed.
     */
    private static function __write(string $path, string $content): void
    {
        if (is_file($path) && file_get_contents($path) === $content) {
            return;
        }

        ensure_directory(dirname($path));
        file_put_contents_safe($path, $content);
    }

    /**
     * Remove the directory of every companion no longer declared.
     */
    private static function __prune(array $names): void
    {
        foreach (glob(Rsx_Project_Paths::companions_build_dir() . '/*', GLOB_ONLYDIR) ?: [] as $directory) {
            if (in_array(basename($directory), $names, true)) {
                continue;
            }

            Rsx_Project_Paths::assert_build_writable($directory, 'companion descriptor removal');

            foreach (glob($directory . '/*') ?: [] as $file) {
                unlink($file);
            }

            rmdir($directory);
        }
    }
}
