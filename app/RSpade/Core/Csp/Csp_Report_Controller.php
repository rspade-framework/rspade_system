<?php

namespace App\RSpade\Core\Csp;

use Illuminate\Http\Request;
use Illuminate\Support\Facades\Log;
use App\RSpade\Core\Controller\Rsx_Controller_Abstract;
use App\RSpade\Core\Debug\Browser_Log_Budget;

/**
 * Csp_Report_Controller - the violation collector named by every policy's report-uri.
 *
 * A browser posts here on its own, with no session cookie it controls, no CSRF token and a
 * vendor-specific content type (`application/csp-report`, or `application/reports+json` for
 * the newer Reporting API). It is a one-way drain into the application log - one
 * `[CSP_VIOLATION] {json}` line (level error, like a browser error) per report - and answers
 * 204 in every case.
 *
 * IT NEVER ERRORS. A collector that 4xx'd a malformed body would teach browsers to retry and
 * turn a reporting channel into an error loop; a collector that threw would fill the
 * application log with noise generated by whatever a page happened to load. A body that is
 * not JSON is recorded (truncated) under an `invalid` key and still answers 204.
 *
 * IT IS BOUNDED, because it is anonymous:
 *   - the size is judged BEFORE the body is read - on the declared Content-Length, then on a
 *     read that stops one byte past MAX_BODY_BYTES - so an oversized POST costs one
 *     `oversized` line and never the memory to hold it;
 *   - a Reporting API batch writes at most Browser_Log_Budget::MAX_ENTRIES_PER_CALL reports,
 *     plus one `dropped` line counting the rest;
 *   - every line goes through Browser_Log_Budget::admit(): an exact report is logged once
 *     per address per 30 minutes, and each first sighting spends a slot of the quota browser
 *     errors share. A repeat, a report past the quota, and any failure of the counter store
 *     are discarded silently;
 *   - each string in a report is cut, the user agent to 300 characters, and the line is
 *     JSON, which can never carry a raw newline.
 * A Reporting API envelope's `age` and `user_agent` are not recorded: the age differs on
 * every delivery of the same report, which would defeat the dedup, and the user agent is
 * recorded once, from the request.
 *
 * NOT A CSRF SURFACE: the collector reads nothing and writes nothing but the log, so it is
 * exempt at the Rsx_Csrf::enforce seam (which sees the path constant, not this class).
 *
 * IT REPORTS UNDER ENFORCEMENT. The policy always blocks; report-uri means every refusal is
 * also recorded, so the log is how a blocked resource is diagnosed - grep it for
 * [CSP_VIOLATION] while adding a widget.
 *
 * BOTH REALMS: the route is declared #[Route] and #[Portal_Route] on this one handler. A
 * portal page's policy names the portal's own collector (Rsx_Csp::report_path('portal') - the
 * path under the portal prefix, or the bare path at the root of the portal's own host), so a
 * portal page's reports reach this collector on whichever host and prefix PORTAL_URL places
 * the portal. Rsx_Csrf exempts both paths.
 *
 * See: php artisan rsx:man csp
 */
class Csp_Report_Controller extends Rsx_Controller_Abstract
{
    /** The prefix every line this collector writes carries. */
    public const LOG_PREFIX = '[CSP_VIOLATION]';

    /** How much of an unparseable body is worth keeping. */
    public const INVALID_BODY_KEPT_BYTES = 4096;

    /**
     * The largest body read as reports. A browser's report is a few hundred bytes and a
     * Reporting API batch a few kilobytes; anything past this is not a browser reporting,
     * and is recorded as one `oversized` line naming its size instead of being read.
     */
    public const MAX_BODY_BYTES = 65536;

    /** The longest line one report may write (its JSON, cut). */
    public const MAX_LINE = 8000;

    /**
     * Accept one violation report (or a Reporting API batch) and record it.
     *
     * Gate is 'public' and must be: the reporter is a browser acting on its own behalf,
     * often on a page nobody is logged into. It carries no authority and reaches no data.
     *
     * @param Request $request
     * @param array $params
     * @return \Symfony\Component\HttpFoundation\Response
     */
    #[Route('/_csp-report', methods: ['POST'])]
    #[Portal_Route('/_csp-report', methods: ['POST'])]
    #[Auth('public')]
    public static function report(Request $request, array $params = [])
    {
        $declared = (int) $request->header('Content-Length', '0');
        if ($declared > self::MAX_BODY_BYTES) {
            static::__record(['oversized' => $declared], $request);

            return response('', 204);
        }

        $body = static::__read_body($request);
        if (strlen($body) > self::MAX_BODY_BYTES) {
            static::__record(['oversized' => 'more than ' . self::MAX_BODY_BYTES . ' bytes'], $request);

            return response('', 204);
        }

        $decoded = json_decode($body, true);
        if (!is_array($decoded)) {
            static::__record(['invalid' => substr($body, 0, self::INVALID_BODY_KEPT_BYTES)], $request);

            return response('', 204);
        }

        // Two wire shapes. `application/csp-report` sends one {"csp-report": {...}}; the
        // Reporting API sends a LIST of {type, url, body} envelopes.
        if (isset($decoded['csp-report'])) {
            static::__record(['report' => $decoded['csp-report']], $request);
        } elseif (array_is_list($decoded)) {
            [$entries, $dropped] = Browser_Log_Budget::entries($decoded);

            foreach ($entries as $entry) {
                if (is_array($entry)) {
                    unset($entry['age'], $entry['user_agent']);
                }
                static::__record(['report' => $entry], $request);
            }

            if ($dropped > 0) {
                static::__record(['dropped' => $dropped], $request);
            }
        } else {
            static::__record(['report' => $decoded], $request);
        }

        return response('', 204);
    }

    /**
     * The body, read one byte past MAX_BODY_BYTES at most - a POST that declared no length
     * (chunked) is never read whole.
     */
    protected static function __read_body(Request $request): string
    {
        $stream = $request->getContent(true);
        $body = '';

        while (!feof($stream) && strlen($body) <= self::MAX_BODY_BYTES) {
            $chunk = fread($stream, self::MAX_BODY_BYTES + 1 - strlen($body));
            if ($chunk === false || $chunk === '') {
                break;
            }
            $body .= $chunk;
        }

        return $body;
    }

    /**
     * Log one line, when Browser_Log_Budget admits it.
     *
     * @param array $payload
     * @param Request $request
     * @return void
     */
    protected static function __record(array $payload, Request $request): void
    {
        $fields = ['user_agent' => Browser_Log_Budget::line((string) $request->header('User-Agent', ''), Browser_Log_Budget::MAX_USER_AGENT)]
            + static::__cut_strings($payload, 0);

        $json = (string) json_encode($fields, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE);
        $line = self::LOG_PREFIX . ' ' . Browser_Log_Budget::line($json, self::MAX_LINE);

        if (Browser_Log_Budget::admit(Browser_Log_Budget::SINK_ERRORS, $line)) {
            Log::error($line);
        }
    }

    /**
     * Every string in a report cut to a location's length; nesting past three levels is
     * recorded as its JSON, cut.
     */
    protected static function __cut_strings($value, int $depth)
    {
        if (is_string($value)) {
            return Browser_Log_Budget::line($value, Browser_Log_Budget::MAX_LOCATION);
        }

        if (!is_array($value)) {
            return $value;
        }

        if ($depth >= 3) {
            return Browser_Log_Budget::line($value, Browser_Log_Budget::MAX_LOCATION);
        }

        $cut = [];
        foreach ($value as $key => $item) {
            $cut[Browser_Log_Budget::line($key, 100)] = static::__cut_strings($item, $depth + 1);
        }

        return $cut;
    }
}
